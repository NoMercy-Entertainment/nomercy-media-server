foreach ($f in $files) {
    if (Test-Path $f) {
        $content = [System.IO.File]::ReadAllText($f, [System.Text.Encoding]::UTF8)
        $updated = $content `
            -replace 'IStorageBackend', 'IStorageDriver' `
            -replace 'SystemIoStorageBackend', 'LocalStorageDriver' `
            -replace '\.StorageBackend\b', '.StorageDriver' `
            -replace '\bstorageBackend\b', 'storageDriver' `
            -replace '\b_storageBackend\b', '_storageDriver' `
            -replace '\bStorageBackend\b', 'StorageDriver' `
            -replace '\.BackendType\b', '.DriverType' `
            -replace '\.BackendConfig\b', '.DriverConfig' `
            -replace '\bBackendType\b', 'DriverType' `
            -replace '\bBackendConfig\b', 'DriverConfig' `
            -replace 'backend_type', 'driver_type' `
            -replace 'backend_config', 'driver_config' `
            -replace 'NoMercy\.Storage\.Backends', 'NoMercy.Storage.Drivers' `
            -replace 'S3StorageBackend', 'S3StorageDriver' `
            -replace 'NfsStorageBackend', 'NfsStorageDriver' `
            -replace 'S3BackendConfig', 'S3DriverConfig' `
            -replace 'NfsBackendConfig', 'NfsDriverConfig'
        if ($updated -ne $content) {
            [System.IO.File]::WriteAllText($f, $updated, [System.Text.Encoding]::UTF8)
            Write-Host "Updated: $f"
        } else {
            Write-Host "No changes: $f"
        }
    } else {
        Write-Host "Not found: $f"
    }
}
