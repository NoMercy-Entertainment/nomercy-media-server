using NoMercy.NmSystem.SystemCalls;
using Serilog.Events;

namespace NoMercy.Service.Hosting;

/// <summary>
/// An <see cref="ILogger{T}"/> for services the bootstrapper builds before the DI
/// container exists. It writes to the setup log, where boot messages already go.
/// </summary>
public sealed class SetupLogger<T> : ILogger<T>
{
    public IDisposable? BeginScope<TState>(TState state)
        where TState : notnull => null;

    public bool IsEnabled(LogLevel logLevel) => logLevel != LogLevel.None;

    public void Log<TState>(
        LogLevel logLevel,
        EventId eventId,
        TState state,
        Exception? exception,
        Func<TState, Exception?, string> formatter
    )
    {
        if (!IsEnabled(logLevel))
            return;

        string message = formatter(state, exception);
        if (exception is not null)
            message = $"{message}: {exception.Message}";

        Logger.Setup(message, ToEventLevel(logLevel));
    }

    private static LogEventLevel ToEventLevel(LogLevel logLevel) =>
        logLevel switch
        {
            LogLevel.Trace => LogEventLevel.Verbose,
            LogLevel.Debug => LogEventLevel.Debug,
            LogLevel.Information => LogEventLevel.Information,
            LogLevel.Warning => LogEventLevel.Warning,
            LogLevel.Error => LogEventLevel.Error,
            _ => LogEventLevel.Fatal,
        };
}
